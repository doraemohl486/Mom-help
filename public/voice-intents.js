// 부모님 음성 명령 알아듣기 (한국어 말 → 의도 목록)
// 브라우저에서는 window.voiceIntent, 테스트에서는 globalThis.voiceIntent 로 쓴다.
(() => {
  const RULES = [
    ["no", /(아니|아냐|싫어|틀려|틀렸|다시 ?할|안 ?넣|넣지 ?마|빼 ?줘|나만|안 ?보여|보여 ?주지 ?마|비밀)/],
    ["yes", /(^|\s)(네|예|응|어|그래|좋아)(요)?(\s|$)|맞아|맞습니다|맞네|넣어|그래도|오케이|보여 ?줘|보여 ?줄게|보여 ?줘도/],
    ["now", /(지금|바로|당장|빨리)/],
    ["arrived", /(도착|다 ?왔|잘 ?왔|왔어)/],
    ["taxi", /(택시|콜택시|차 ?불러|불러 ?줘|불러 ?주)/],
    ["transit", /(버스|지하철|전철|대중교통)/],
    ["family", /(아들|딸|자녀|애들|며느리|사위|손주|손자|손녀|태워|데려다|데리러)/],
    ["prev", /(지난 ?달|저번 ?달|이전 ?달)/],
    ["next", /다음 ?달/],
    ["calendar", /(달력|이번 ?달|일정 ?(보여|봐|뭐 ?있))/],
    ["back", /(돌아가|처음으로|그만|닫아|나가)/],
    ["repeat", /(다시 ?말|뭐라고|읽어|못 ?들었|한 ?번 ?더|소리로)/],
    ["add", /(일정 ?(알려|추가|넣|생겼)|약속 ?(있|생겼)|예약 ?(했|있|생겼))/],
  ];
  const SCHEDULE = /(\d{1,2}|한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|열한|열두)\s*시|[월화수목금토일]요일|내일|모레|\d{1,2}\s*월\s*\d{1,2}\s*일|\d{1,2}\s*\/\s*\d{1,2}/;

  /** 말한 내용에서 알아들은 의도들 (앞에 있을수록 우선) */
  function voiceIntent(text) {
    const t = String(text ?? "").replace(/[.,!?~]/g, " ").replace(/\s+/g, " ").trim();
    if (!t) return [];
    const out = RULES.filter(([, re]) => re.test(t)).map(([k]) => k);
    if (SCHEDULE.test(t)) out.push("schedule");
    return out;
  }
  globalThis.voiceIntent = voiceIntent;
})();
